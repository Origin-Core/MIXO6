-- MIXO6 Supabase schema. Paste this file into Supabase Dashboard > SQL Editor and run it.
-- Auth passwords are handled only by Supabase Auth. Do not add password columns.

begin;

grant usage on schema public to anon, authenticated;

create table if not exists public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    username text not null unique,
    avatar text not null default '◈' check (avatar in ('◈','✦','⬡','◆','◉')),
    main_game text not null default 'CS2' check (char_length(main_game) between 1 and 60),
    created_at timestamptz not null default now(),
    last_seen_at timestamptz not null default now(),
    constraint profiles_username_format check (username ~ '^[a-z0-9_]{3,20}$')
);
create unique index if not exists profiles_username_lower_uidx on public.profiles (lower(username));

create table if not exists public.lobbies (
    id bigint generated by default as identity primary key,
    creator_id uuid not null references public.profiles(id) on delete cascade,
    game text not null check (char_length(game) between 1 and 60),
    server_address text not null check (char_length(server_address) between 1 and 300),
    server_label text not null default 'Custom' check (char_length(server_label) between 1 and 80),
    description text not null default '' check (char_length(description) <= 500),
    status text not null default 'open' check (status in ('open','full','closed')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
create index if not exists lobbies_open_created_idx on public.lobbies(status, created_at desc);
create index if not exists lobbies_game_lower_idx on public.lobbies(lower(game));
create index if not exists lobbies_creator_idx on public.lobbies(creator_id);
create unique index if not exists lobbies_one_open_per_creator on public.lobbies(creator_id) where status='open';

create table if not exists public.lobby_members (
    lobby_id bigint not null references public.lobbies(id) on delete cascade,
    user_id uuid not null references public.profiles(id) on delete cascade,
    role text not null check (role in ('creator','player')),
    joined_at timestamptz not null default now(),
    primary key (lobby_id, user_id)
);
create index if not exists lobby_members_user_idx on public.lobby_members(user_id);

-- Create a public profile after Auth signup. Usernames are normalized to lowercase.
create or replace function public.mixo6_handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    desired_username text;
begin
    desired_username := lower(btrim(coalesce(new.raw_user_meta_data ->> 'username', '')));
    if desired_username !~ '^[a-z0-9_]{3,20}$' then
        raise exception 'MIXO6_USERNAME_INVALID';
    end if;
    if exists (select 1 from public.profiles p where lower(p.username) = desired_username) then
        raise exception 'MIXO6_USERNAME_TAKEN';
    end if;
    insert into public.profiles(id, username, avatar, main_game)
    values (new.id, desired_username, '◈', 'CS2');
    return new;
end;
$$;

drop trigger if exists mixo6_on_auth_user_created on auth.users;
create trigger mixo6_on_auth_user_created
after insert on auth.users
for each row execute function public.mixo6_handle_new_auth_user();

alter table public.profiles enable row level security;
alter table public.lobbies enable row level security;
alter table public.lobby_members enable row level security;

drop policy if exists profiles_public_read on public.profiles;
create policy profiles_public_read on public.profiles for select to anon, authenticated using (true);
drop policy if exists profiles_update_self on public.profiles;
create policy profiles_update_self on public.profiles for update to authenticated
using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists lobbies_public_open_read on public.lobbies;
-- Direct reads, where granted, are restricted to open rows and non-sensitive columns only.
create policy lobbies_public_open_read on public.lobbies for select to anon, authenticated using (status = 'open');
drop policy if exists lobby_members_count_open on public.lobby_members;
create policy lobby_members_count_open on public.lobby_members for select to anon, authenticated
using (exists (select 1 from public.lobbies l where l.id = lobby_members.lobby_id and l.status = 'open'));

-- Deliberately do not grant direct table access to lobbies or lobby_members.
-- In particular, server_address must never be available through the public REST list.
revoke all on public.profiles from anon, authenticated;
grant select on public.profiles to anon, authenticated;
grant update (avatar, main_game) on public.profiles to authenticated;
revoke all on public.lobbies from anon, authenticated;
revoke all on public.lobby_members from anon, authenticated;
-- Column-level grants intentionally exclude the secret server_address and lobby member user_id.
grant select (id, creator_id, game, server_label, description, status, created_at) on public.lobbies to anon, authenticated;
grant select (lobby_id) on public.lobby_members to anon, authenticated;

-- Safe invoker view: it intentionally omits server_address, creator_id, and lobby member user_id.
create or replace view public.lobby_cards
with (security_barrier = true, security_invoker = true)
as
select
    l.id,
    l.game,
    l.server_label,
    l.description,
    l.status,
    p.username as creator_username,
    p.avatar as creator_avatar,
    (p.last_seen_at >= now() - interval '5 minutes') as creator_online,
    (select count(*)::integer from public.lobby_members lm where lm.lobby_id = l.id) as member_count,
    l.created_at
from public.lobbies l
join public.profiles p on p.id = l.creator_id
where l.status = 'open';
revoke all on public.lobby_cards from public;
grant select on public.lobby_cards to anon, authenticated;

create or replace function public.mixo6_heartbeat()
returns boolean
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare caller_id uuid := auth.uid();
begin
    if caller_id is null then raise exception 'AUTH_REQUIRED'; end if;
    update public.profiles set last_seen_at = now() where id = caller_id;
    return found;
end;
$$;

create or replace function public.mixo6_create_lobby(
    p_game text,
    p_server_address text,
    p_server_label text default 'Custom',
    p_description text default ''
)
returns bigint
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
    new_lobby_id bigint;
    caller_id uuid := auth.uid();
begin
    if caller_id is null then raise exception 'AUTH_REQUIRED'; end if;
    if char_length(btrim(coalesce(p_game,''))) not between 1 and 60 then raise exception 'INVALID_GAME'; end if;
    if char_length(btrim(coalesce(p_server_address,''))) not between 1 and 300 then raise exception 'INVALID_SERVER_ADDRESS'; end if;
    if char_length(btrim(coalesce(p_server_label,'Custom'))) not between 1 and 80 then raise exception 'INVALID_SERVER_LABEL'; end if;
    if char_length(coalesce(p_description,'')) > 500 then raise exception 'DESCRIPTION_TOO_LONG'; end if;

    insert into public.lobbies(creator_id, game, server_address, server_label, description)
    values (caller_id, btrim(p_game), btrim(p_server_address), btrim(coalesce(p_server_label,'Custom')), btrim(coalesce(p_description,'')))
    returning id into new_lobby_id;

    insert into public.lobby_members(lobby_id, user_id, role)
    values (new_lobby_id, caller_id, 'creator');
    update public.profiles set last_seen_at = now() where id = caller_id;
    return new_lobby_id;
exception when unique_violation then
    raise exception 'ACTIVE_LOBBY_EXISTS';
end;
$$;

create or replace function public.mixo6_join_lobby(p_lobby_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
    caller_id uuid := auth.uid();
    target public.lobbies%rowtype;
    member_count integer;
    creator_name text;
    already_member boolean;
begin
    if caller_id is null then raise exception 'AUTH_REQUIRED'; end if;
    select * into target from public.lobbies where id = p_lobby_id for update;
    if not found then raise exception 'LOBBY_NOT_FOUND'; end if;
    if target.status = 'closed' then raise exception 'LOBBY_CLOSED'; end if;

    select exists(select 1 from public.lobby_members where lobby_id = p_lobby_id and user_id = caller_id)
    into already_member;
    select count(*)::integer into member_count from public.lobby_members where lobby_id = p_lobby_id;

    if not already_member then
        if target.creator_id = caller_id then
            raise exception 'CREATOR_ALREADY_MEMBER';
        end if;
        if target.status = 'full' or member_count >= 2 then raise exception 'LOBBY_FULL'; end if;
        insert into public.lobby_members(lobby_id, user_id, role) values (p_lobby_id, caller_id, 'player');
        member_count := member_count + 1;
        if member_count >= 2 then update public.lobbies set status = 'full', updated_at = now() where id = p_lobby_id; end if;
    end if;

    select username into creator_name from public.profiles where id = target.creator_id;
    update public.profiles set last_seen_at = now() where id = caller_id;
    return jsonb_build_object(
        'lobbyId', target.id,
        'serverAddress', target.server_address,
        'creatorUsername', creator_name,
        'game', target.game,
        'description', target.description
    );
end;
$$;

create or replace function public.mixo6_close_lobby(p_lobby_id bigint)
returns boolean
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
    caller_id uuid := auth.uid();
begin
    if caller_id is null then raise exception 'AUTH_REQUIRED'; end if;
    update public.lobbies set status='closed', updated_at=now()
    where id=p_lobby_id and creator_id=caller_id and status in ('open','full');
    if not found then raise exception 'LOBBY_NOT_FOUND_OR_NOT_OWNER'; end if;
    return true;
end;
$$;

revoke all on function public.mixo6_handle_new_auth_user() from public, anon, authenticated;
revoke all on function public.mixo6_heartbeat() from public, anon, authenticated;
revoke all on function public.mixo6_create_lobby(text,text,text,text) from public, anon, authenticated;
revoke all on function public.mixo6_join_lobby(bigint) from public, anon, authenticated;
revoke all on function public.mixo6_close_lobby(bigint) from public, anon, authenticated;
grant execute on function public.mixo6_heartbeat() to authenticated;
grant execute on function public.mixo6_create_lobby(text,text,text,text) to authenticated;
grant execute on function public.mixo6_join_lobby(bigint) to authenticated;
grant execute on function public.mixo6_close_lobby(bigint) to authenticated;

notify pgrst, 'reload schema';
commit;
